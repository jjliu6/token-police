function t(key, vars) {
  const pack = I18N[currentLang()] || I18N.en;
  let s = pack[key] || I18N.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split('{' + k + '}').join(vars[k]);
    });
  }
  return s;
}

function applyI18n() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = LANG_HTML[currentLang()] || 'en';
  const brand = document.getElementById('brand-name');
  if (brand) brand.textContent = t('brand');
  const legend = document.getElementById('legend');
  if (legend) legend.textContent = t('legend');
  const btn = document.getElementById('refresh');
  if (btn && !btn.disabled) btn.textContent = t('refresh');
  const langBtns = document.querySelectorAll('#langs [data-lang]');
  for (let i = 0; i < langBtns.length; i++) {
    const b = langBtns[i];
    const on = b.dataset.lang === currentLang();
    b.classList.toggle('on', on);
    b.setAttribute('aria-pressed', on ? 'true' : 'false');
  }
  const gearBtn = document.getElementById('gear');
  if (gearBtn) gearBtn.title = t('gearTitle');
  const shareBtn = document.getElementById('share');
  if (shareBtn) {
    shareBtn.textContent = t('share');
    shareBtn.title = t('shareTitle');
  }
  const logsBtn = document.getElementById('logs');
  if (logsBtn) {
    logsBtn.textContent = t('logs');
    logsBtn.title = t('logs');
  }
  const dispatchBtn = document.getElementById('dispatch-toggle');
  if (dispatchBtn) {
    dispatchBtn.textContent = t('dispatch');
    dispatchBtn.title = t('dispatchOpen');
  }
  const crosscheckBtn = document.getElementById('crosscheck-toggle');
  if (crosscheckBtn) {
    crosscheckBtn.textContent = t('crosscheck');
    crosscheckBtn.title = t('crosscheckOpen');
  }
  if (typeof fillShareCard === 'function') fillShareCard();
  if (typeof fillLogsView === 'function') fillLogsView();
  if (typeof renderDispatch === 'function') renderDispatch();
  if (typeof renderCrosscheck === 'function') renderCrosscheck();
}

function applyStoredLang(lang) {
  uiLang = knownLang(lang);
  applyI18n();
}

function loadLang(done) {
  const finish = () => { if (typeof done === 'function') done(); };
  if (!chrome.storage || !chrome.storage.local || !chrome.storage.local.get) {
    applyStoredLang('en');
    finish();
    return;
  }
  chrome.storage.local.get(['uiLang'], (res) => {
    applyStoredLang(res && res.uiLang);
    finish();
  });
}

function setLang(lang, done) {
  applyStoredLang(lang);
  const finish = () => { if (typeof done === 'function') done(); };
  if (chrome.storage && chrome.storage.local && chrome.storage.local.set) {
    chrome.storage.local.set({ uiLang }, finish);
  } else {
    finish();
  }
}
